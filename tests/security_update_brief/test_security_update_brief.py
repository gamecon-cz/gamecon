class ParsingTest(unittest.TestCase):
    def test_composer_lock_keeps_scope_repository_and_reference(self):
        packages = brief.parse_composer_lock(composer_lock([('symfony/yaml', 'v7.4.14', 'aaa')], [('phpunit/phpunit', '12.5.1', 'bbb')]))
        self.assertEqual('https://github.com/symfony/yaml', packages['symfony/yaml'][0].repository)
        self.assertEqual('aaa', packages['symfony/yaml'][0].reference)
        self.assertFalse(packages['symfony/yaml'][0].dev)
        self.assertTrue(packages['phpunit/phpunit'][0].dev)

    def test_yarn_lock_reads_scoped_names_shared_headers_and_several_versions(self):
        packages = brief.parse_yarn_lock(YARN_LOCK)
        self.assertEqual(['7.24.7'], [package.version for package in packages['@babel/core']])
        self.assertEqual(['3.2.1', '4.3.0'], brief.ordered_versions(brief.locked_entries(packages['ansi-styles'])))
        self.assertEqual(1, len(packages['lodash']))

    def test_yarn_berry_lock_skips_metadata_and_workspaces_and_names_the_real_package_behind_an_alias(self):
        packages = brief.parse_yarn_lock(YARN_BERRY_LOCK)
        self.assertEqual(['bar', 'lodash'], sorted(packages))
        self.assertEqual('1.2.3', packages['bar'][0].version)

    def test_yarn_1_aliases_name_the_real_package_too(self):
        packages = brief.parse_yarn_lock('"foo@npm:bar@^1.0.0":\n  version "1.2.3"\n\n"@a/x@npm:@b/y@^2.0.0":\n  version "2.1.0"\n\nlodash@^4.17.21:\n  version "4.17.21"\n')
        self.assertEqual(['@b/y', 'bar', 'lodash'], sorted(packages))
        self.assertEqual('foo', brief.package_name_of('foo@^1.0.0'))
        self.assertEqual('bar', brief.package_name_of('foo@npm:bar@^1.0.0'))
        self.assertEqual('lodash', brief.package_name_of('lodash@npm:^4.17.21'))

    def test_a_pre_release_sorts_before_the_stable_release_of_the_same_numbers(self):
        entries = {('1.0.0', None), ('1.0.0-beta', None), ('1.0.0-alpha', None), ('0.9.0', None)}
        self.assertEqual(['0.9.0', '1.0.0-alpha', '1.0.0-beta', '1.0.0'], brief.ordered_versions(entries))

    def test_pre_release_numbers_compare_as_numbers_and_build_or_patch_suffixes_are_stable(self):
        entries = {(version, None) for version in ('1.0.0-rc.10', '1.0.0-rc.2', '1.0.0', '1.0.0+build', '1.0.0-p1')}
        self.assertEqual(['1.0.0-rc.2', '1.0.0-rc.10', '1.0.0', '1.0.0+build', '1.0.0-p1'], brief.ordered_versions(entries))

    def test_odd_version_text_is_ordered_deterministically_and_never_raises(self):
        self.assertEqual([(0, 1, ''), (1, 0, '²')], brief.natural_key('1²'))
        brief.version_order('1.0.0²')
        self.assertNotEqual(brief.version_order('1.0.0-rc.01'), brief.version_order('1.0.0-rc.1'))
        for entries in ([('1.0.0-rc.01', None), ('1.0.0-rc.1', None)], [('1.0.0-rc.1', None), ('1.0.0-rc.01', None)]):
            self.assertEqual(['1.0.0-rc.01', '1.0.0-rc.1'], brief.ordered_versions(entries))

    def test_a_version_with_an_absurdly_long_digit_run_does_not_abort_the_brief(self):
        for version in ('1' * 5000, '1.0-rc.' + '2' * 5000, 'v' + '9' * 40 + '.1'):
            brief.version_order(version)
            brief.jump_between([version], ['1.0.0'])
        self.assertEqual(2, len(brief.ordered_versions({('1' * 5000, None), ('2', None)})))

    def test_a_manifest_section_that_is_an_empty_list_is_no_dependencies(self):
        self.assertEqual({'a/b': '^1'}, brief.requirements_of({'require': {'a/b': '^1'}, 'require-dev': []}, 'php'))

    def test_an_alias_in_the_manifest_makes_the_installed_package_direct(self):
        requirements = brief.requirements_of({'dependencies': {'foo': 'npm:bar@^1', 'baz': 'npm:@scope/qux@^2', 'plain': '^4'}}, 'js')
        self.assertEqual({'foo', 'bar', 'baz', '@scope/qux', 'plain'}, set(requirements))
        self.assertEqual('npm:bar@^1', requirements['bar'])

    def test_both_sections_of_a_manifest_count_as_direct(self):
        self.assertEqual({'svelte': '^4', 'vite': '^5'}, brief.requirements_of({'dependencies': {'svelte': '^4'}, 'devDependencies': {'vite': '^5'}}, 'js'))


class ComposerDetailsTest(unittest.TestCase):
    def test_the_lock_entry_gives_release_date_type_requirements_and_namespaces(self):
        text = rich_lock([{'name': 'a/b', 'version': '1.0.0', 'reference': 'r', 'type': 'symfony-bundle', 'time': '2026-09-30T08:00:00+00:00',
                           'require': {'php': '>=8.2', 'c/d': '^2'}, 'namespaces': ['A\\B\\', 'A\\B\\Extra\\']}])
        package = brief.parse_composer_lock(text)['a/b'][0]
        self.assertEqual(('2026-09-30', 'symfony-bundle', {'php': '>=8.2', 'c/d': '^2'}, ['A\\B\\', 'A\\B\\Extra\\']),
                         (package.released, package.kind, package.requires, package.namespaces))

    def test_composer_patches_v2_entries_given_as_objects_are_read_too(self):
        manifest = {'extra': {'patches': {'a/b': [{'description': 'x', 'url': 'patches/x.patch'}, 'patches/y.patch'],
                                          'c/d': {'Fix': {'url': 'patches/z.patch', 'sha256': 'abc'}}}}}
        self.assertEqual({'a/b': ['patches/x.patch', 'patches/y.patch'], 'c/d': ['patches/z.patch']}, brief.composer_patches(manifest))

    def test_a_lock_with_null_sections_or_a_non_object_source_still_parses(self):
        packages = brief.parse_composer_lock(json.dumps({'packages': [{'name': 'a/b', 'version': '1', 'source': 'nope'}], 'packages-dev': None}))
        self.assertEqual(['a/b'], list(packages))
        self.assertIsNone(packages['a/b'][0].repository)

    def test_a_lock_entry_without_those_keys_or_with_odd_ones_still_parses(self):
        odd = json.dumps({'packages': [{'name': 'a/b', 'version': '1', 'require': [], 'autoload': {'psr-4': []}, 'time': None},
                                       {'name': 'c/d', 'version': '2', 'autoload': {'psr-4': {'': 'src/', 'C\\D\\': 'lib/'}}}]})
        packages = brief.parse_composer_lock(odd)
        self.assertEqual(({}, [], None), (packages['a/b'][0].requires, packages['a/b'][0].namespaces, packages['a/b'][0].released))
        self.assertEqual(['C\\D\\'], packages['c/d'][0].namespaces)

    def test_psr_0_prefixes_count_as_namespaces_and_a_package_that_autoloads_only_classes_or_files_is_marked(self):
        lock = json.dumps({'packages': [
            {'name': 'a/old', 'version': '1', 'autoload': {'psr-0': {'Old_': 'lib/', 'Old\\Ns\\': 'lib/', '': 'lib/'}}},
            {'name': 'b/classes', 'version': '1', 'autoload': {'classmap': ['src/']}},
            {'name': 'c/files', 'version': '1', 'autoload': {'files': ['functions.php']}},
            {'name': 'd/none', 'version': '1'},
            {'name': 'e/both', 'version': '1', 'autoload': {'psr-4': {'E\\': 'src/'}, 'classmap': ['extra/']}},
            {'name': 'f/root', 'version': '1', 'autoload': {'psr-4': {'': 'src/'}}},
            {'name': 'g/nothing', 'version': '1', 'autoload': {'exclude-from-classmap': ['tests/']}},
        ]})
        packages = {name: versions[0] for name, versions in brief.parse_composer_lock(lock).items()}
        self.assertEqual(['Old\\Ns\\', 'Old_'], packages['a/old'].namespaces)
        self.assertEqual(['E\\'], packages['e/both'].namespaces)
        self.assertEqual({'a/old': False, 'b/classes': True, 'c/files': True, 'd/none': False, 'e/both': False, 'f/root': True, 'g/nothing': False},
                         {name: package.classes_only for name, package in packages.items()})

    def test_a_long_range_is_cut_between_two_ranges_not_inside_one(self):
        ranges = '|'.join('>=%d.0.0,<%d.1.0' % (number, number) for number in range(1, 30))
        shown = brief.shortened_range(ranges)
        self.assertTrue(shown.endswith('|…'))
        self.assertLessEqual(len(shown), 162)
        for part in shown[:-2].split('|'):
            self.assertRegex(part, r'^>=\d+\.0\.0,<\d+\.1\.0$')
        self.assertEqual('>=1,<2', brief.shortened_range('>=1,<2'))
        self.assertEqual('x' * 160 + '|…', brief.shortened_range('x' * 400))

    def test_requirement_changes_name_what_was_added_removed_and_moved_and_cap_the_list(self):
        changes = brief.requirement_changes({'php': '>=8.1', 'x/old': '^1', 'x/same': '^1', 'x/moved': '^1'},
                                            {'php': '>=8.2', 'x/new': '^3', 'x/same': '^1', 'x/moved': '^2'})
        self.assertEqual({'added': {'x/new': '^3'}, 'removed': ['x/old'], 'changed': {'php': ['>=8.1', '>=8.2'], 'x/moved': ['^1', '^2']}}, changes)
        self.assertEqual({}, brief.requirement_changes({'a/b': '^1'}, {'a/b': '^1'}))
        many = brief.requirement_changes({}, {'p/%d' % number: '^1' for number in range(10)})
        self.assertEqual(brief.MAX_LISTED_CHANGES, len(many['added']))
        self.assertEqual(4, many['added_more'])

    def test_reverse_requirements_say_which_locked_packages_require_a_package(self):
        packages = brief.parse_composer_lock(rich_lock([
            {'name': 'a/one', 'version': '1', 'reference': 'x', 'require': {'c/lib': '^1', 'php': '>=8'}},
            {'name': 'a/two', 'version': '1', 'reference': 'x', 'require': {'c/lib': '^1'}},
            {'name': 'c/lib', 'version': '1', 'reference': 'x'},
        ]))
        required_by = brief.reverse_requirements(packages)
        self.assertEqual({'a/one', 'a/two'}, required_by['c/lib'])
        self.assertNotIn('a/one', required_by)

    def test_manifest_requirements_and_patches_in_both_shapes_composer_patches_accepts(self):
        manifest = {'require': {'a/b': '^1.2', 'php': '^8.5'}, 'require-dev': {'c/d': '^3'},
                    'extra': {'patches': {'a/b': ['patches/one.patch'], 'x/y': {'Fix the thing': 'patches/two.patch', 'Other': 'patches/three.patch'}}}}
        self.assertEqual({'a/b': '^1.2', 'php': '^8.5', 'c/d': '^3'}, brief.requirements_of(manifest, 'php'))
        self.assertEqual({'a/b': ['patches/one.patch'], 'x/y': ['patches/two.patch', 'patches/three.patch']}, brief.composer_patches(manifest))
        self.assertEqual({}, brief.composer_patches({'extra': {'patches': 'no'}}))
        self.assertEqual({}, brief.requirements_of([], 'php'))


