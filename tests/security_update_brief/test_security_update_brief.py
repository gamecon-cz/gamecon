        packages = {'a/low': [brief.LockedPackage('a/low', '1')]}
        packages.update({'a/user%d' % number: [brief.LockedPackage('a/user%d' % number, '1', requires={'a/low': '^1'})] for number in range(8)})
        old = {name: [brief.LockedPackage(name, '0')] for name in packages}
