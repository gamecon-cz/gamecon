def composer_lock(packages, dev_packages=()):
    def entry(name, version, reference):
        return {'name': name, 'version': version, 'source': {'type': 'git', 'url': 'https://github.com/%s.git' % name, 'reference': reference}}
    return json.dumps({
        'packages': [entry(*package) for package in packages],
        'packages-dev': [entry(*package) for package in dev_packages],
    })


def rich_lock(packages):
    """A composer.lock from dicts: name, version, reference and optionally require, namespaces, time, type, dev."""
    def entry(package):
        locked = {'name': package['name'], 'version': package['version'], 'type': package.get('type', 'library'),
                  'source': {'type': 'git', 'url': 'https://github.com/%s.git' % package['name'], 'reference': package['reference']},
                  'require': package.get('require', {}), 'time': package.get('time', '2026-10-01T10:00:00+00:00')}
        if package.get('namespaces'):
            locked['autoload'] = {'psr-4': {namespace: 'src/' for namespace in package['namespaces']}}
        return locked
    return json.dumps({'packages': [entry(package) for package in packages if not package.get('dev')],
                       'packages-dev': [entry(package) for package in packages if package.get('dev')]})


def yarn_lock(entries):
    return '# yarn lockfile v1\n\n\n' + '\n'.join('%s@^1.0.0:\n  version "%s"\n' % entry for entry in entries)


