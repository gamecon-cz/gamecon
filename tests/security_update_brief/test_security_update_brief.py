class ReportTest(unittest.TestCase):
    def lock(self, base, head, direct=()):
        return brief.Lock(path='composer.lock', ecosystem='php', base=brief.parse_composer_lock(base),
                          head=brief.parse_composer_lock(head), direct_names=set(direct))

    def advisory(self, package, advisory_id='GHSA-1'):
        return brief.Advisory(advisory_id, package, 'high', 'A title', '<7.4.18', 'https://github.com/advisories/' + advisory_id)

    def test_fixing_package_and_companion_are_told_apart(self):
        lock = self.lock(
            composer_lock([('symfony/yaml', 'v7.4.14', 'old1'), ('symfony/string', 'v7.4.14', 'old2')]),
            composer_lock([('symfony/yaml', 'v7.4.18', 'new1'), ('symfony/string', 'v7.4.18', 'new2')]),
            direct=['symfony/yaml'],
        )
        report = brief.build_lock_report(lock, [self.advisory('symfony/yaml')], [], None)
        lines = {line['package']: line for line in report['packages']}
        self.assertEqual(['GHSA-1'], lines['symfony/yaml']['fixes'])
        self.assertTrue(lines['symfony/yaml']['direct'])
        self.assertEqual([], lines['symfony/string']['fixes'])
        self.assertEqual('https://github.com/symfony/yaml/compare/old1...new1', lines['symfony/yaml']['compare'])
        self.assertEqual('patch', lines['symfony/yaml']['jump'])

    def test_unchanged_packages_are_left_out_and_added_and_removed_are_marked(self):
        lock = self.lock(
            composer_lock([('a/kept', '1.0.0', 'x'), ('a/gone', '1.0.0', 'x')]),
            composer_lock([('a/kept', '1.0.0', 'x'), ('a/new', '2.0.0', 'y')]),
        )
        report = brief.build_lock_report(lock, [], [], None)
        self.assertEqual({'a/gone': 'removed', 'a/new': 'added'}, {line['package']: line['jump'] for line in report['packages']})

    def test_a_package_merged_into_one_version_is_still_locked_not_removed(self):
        base = brief.parse_yarn_lock('foo@^1.0.0:\n  version "1.0.0"\n\nfoo@^2.0.0:\n  version "2.0.0"\n')
        head = brief.parse_yarn_lock('foo@^1.0.0, foo@^2.0.0:\n  version "2.0.0"\n')
        lock = brief.Lock(path='yarn.lock', ecosystem='js', base=base, head=head)
        report = brief.build_lock_report(lock, [], [], None)
        line = report['packages'][0]
        self.assertEqual(('1.0.0', '2.0.0', 'deduplicated'), (line['from'], line['to'], line['jump']))
        self.assertEqual({'deduplicated': 1}, report['counts'])

    def test_a_second_version_of_a_package_is_reported_as_a_duplicate(self):
        base = brief.parse_yarn_lock('foo@^1.0.0:\n  version "1.0.0"\n')
        head = brief.parse_yarn_lock('foo@^1.0.0:\n  version "1.0.0"\n\nfoo@^2.0.0:\n  version "2.0.0"\n')
        line = brief.build_lock_report(brief.Lock(path='yarn.lock', ecosystem='js', base=base, head=head), [], [], None)['packages'][0]
        self.assertEqual(('1.0.0', '2.0.0', 'duplicated'), (line['from'], line['to'], line['jump']))

    def test_the_compare_link_follows_the_highest_changed_version_not_the_alphabetically_last(self):
        lock = self.lock(
            composer_lock([('a/b', '9.0.0', 'old9'), ('a/b', '10.0.0', 'old10')]),
            composer_lock([('a/b', '9.1.0', 'new9'), ('a/b', '10.1.0', 'new10')]),
        )
        line = brief.build_lock_report(lock, [], [], None)['packages'][0]
        self.assertEqual(['9.0.0', '10.0.0'], line['from'])
        self.assertEqual('https://github.com/a/b/compare/old10...new10', line['compare'])

    def test_a_line_carries_source_dates_requirements_constraint_patches_dependents_and_usage(self):
        old = rich_lock([
            {'name': 'a/direct', 'version': 'v1.0.0', 'reference': 'olddirectref0000', 'require': {'php': '>=8.1'}, 'namespaces': ['A\\Direct\\']},
            {'name': 'a/transitive', 'version': 'v2.0.0', 'reference': 'oldtransref0000', 'type': 'symfony-bundle'},
            {'name': 'a/root', 'version': 'v1.0.0', 'reference': 'rootref', 'require': {'a/transitive': '^2', 'a/direct': '^1'}},
        ])
        new = rich_lock([
            {'name': 'a/direct', 'version': 'v1.1.0', 'reference': 'newdirectref0000', 'require': {'php': '>=8.2', 'x/new': '^1'},
             'namespaces': ['A\\Direct\\'], 'time': '2026-10-20T00:00:00+00:00'},
            {'name': 'a/transitive', 'version': 'v2.0.1', 'reference': 'newtransref0000', 'type': 'symfony-bundle'},
            {'name': 'a/root', 'version': 'v1.0.0', 'reference': 'rootref', 'require': {'a/transitive': '^2', 'a/direct': '^1'}},
        ])
        lock = brief.Lock('composer.lock', 'php', brief.parse_composer_lock(old), brief.parse_composer_lock(new),
                          direct_names={'a/direct', 'a/root'}, requirements={'a/direct': '^1.1', 'a/root': '^1'},
                          base_requirements={'a/direct': '^1.0', 'a/root': '^1'}, patches={'a/direct': ['patches/direct.patch']},
                          usage={'a/direct': {'src': 2, 'tests': 1}})
        lines = {line['package']: line for line in brief.build_lock_report(lock, [], [], None)['packages']}
        direct = lines['a/direct']
        self.assertEqual(('https://github.com/a/direct', 'olddirectref0000', 'newdirectref0000', '2026-10-20'),
                         (direct['repository'], direct['from_ref'], direct['to_ref'], direct['released']))
        self.assertEqual({'added': {'x/new': '^1'}, 'changed': {'php': ['>=8.1', '>=8.2']}}, direct['requires'])
        self.assertEqual(('^1.1', '^1.0'), (direct['constraint'], direct['constraint_was']))
        self.assertEqual((['patches/direct.patch'], ['A\\Direct\\'], {'src': 2, 'tests': 1}), (direct['patches'], direct['namespaces'], direct['used_in']))
        self.assertNotIn('required_by', direct)
        transitive = lines['a/transitive']
        self.assertEqual((['a/root'], 'symfony-bundle'), (transitive['required_by'], transitive['kind']))
        self.assertNotIn('constraint', transitive)
        self.assertNotIn('a/root', lines)

    def test_a_constraint_that_did_not_change_is_given_once(self):
        lock = brief.Lock('composer.lock', 'php', brief.parse_composer_lock(composer_lock([('a/b', '1.0.0', 'old')])),
                          brief.parse_composer_lock(composer_lock([('a/b', '1.0.1', 'new')])),
                          direct_names={'a/b'}, requirements={'a/b': '^1'}, base_requirements={'a/b': '^1'})
        line = brief.build_lock_report(lock, [], [], None)['packages'][0]
        self.assertEqual('^1', line['constraint'])
        self.assertNotIn('constraint_was', line)

    def test_a_repository_that_is_not_on_github_gets_refs_instead_of_a_compare_link(self):
        self.assertIsNone(brief.compare_url('https://gitlab.com/a/b', 'x', 'y'))
        self.assertIsNone(brief.compare_url('https://github.com/a/b', 'x', None))
        packages = brief.parse_composer_lock(json.dumps({'packages': [
            {'name': 'a/b', 'version': '1.0.0', 'source': {'url': 'https://gitlab.com/a/b.git', 'reference': 'old'}}]}))
        head = brief.parse_composer_lock(json.dumps({'packages': [
            {'name': 'a/b', 'version': '1.0.1', 'source': {'url': 'https://gitlab.com/a/b.git', 'reference': 'new'}}]}))
        line = brief.build_lock_report(brief.Lock('composer.lock', 'php', packages, head), [], [], None)['packages'][0]
        self.assertEqual(('https://gitlab.com/a/b', 'old', 'new'), (line['repository'], line['from_ref'], line['to_ref']))
        self.assertNotIn('compare', line)

    def test_a_branch_package_whose_commit_moved_is_reported_although_its_version_is_the_same(self):
        lock = self.lock(composer_lock([('a/branch', 'dev-main', 'old')]), composer_lock([('a/branch', 'dev-main', 'new')]))
        line = brief.build_lock_report(lock, [], [], None)['packages'][0]
        self.assertEqual(('dev-main', 'dev-main', 'reference'), (line['from'], line['to'], line['jump']))
        self.assertEqual('https://github.com/a/branch/compare/old...new', line['compare'])


