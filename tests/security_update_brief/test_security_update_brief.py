    def test_the_audit_runs_on_the_lock_of_each_state_with_only_the_audit_settings_of_the_base_branch(self):
        base_json = json.dumps({'config': {'audit': {'ignore': ['GHSA-known']}}, 'repositories': [{'type': 'composer', 'url': 'https://base.example'}]})
        head_json = json.dumps({'config': {'audit': {'ignore': ['GHSA-hidden']}}, 'repositories': [{'type': 'composer', 'url': 'https://evil.example'}]})
        base_lock, head_lock = composer_lock([('a/b', '1.0.0', 'old')]), composer_lock([('a/b', '1.0.1', 'new')])
        self.commit({'composer.json': base_json, 'composer.lock': base_lock})
        self.commit({'composer.json': head_json, 'composer.lock': head_lock})
        seen = []

        def audit(directory):
            with open(os.path.join(directory, 'composer.json')) as manifest_file, open(os.path.join(directory, 'composer.lock')) as lock_file:
                seen.append((json.load(manifest_file), lock_file.read()))
            return []

        with mock.patch.object(brief, 'composer_advisories', side_effect=audit):
            self.run_brief()
        audit_only = {'config': {'audit': {'ignore': ['GHSA-known']}}}
        self.assertEqual([(audit_only, base_lock), (audit_only, head_lock)], seen)

