class TableTest(unittest.TestCase):
    def report(self, lines, ecosystem='php'):
        return {'path': 'composer.lock', 'ecosystem': ecosystem, 'packages': lines, 'counts': {}, 'advisories': [], 'remaining': [], 'lookup_error': None}

    def line(self, name, **extra):
        line = {'package': name, 'from': '1.0.0', 'to': '1.0.1', 'jump': 'patch', 'direct': False, 'fixes': []}
        line.update(extra)
        return line

    def test_the_table_lists_name_versions_source_and_fixes_of_the_packages_that_matter(self):
        text = brief.render_lock_report(self.report([
            self.line('a/fixed', fixes=['GHSA-1', 'GHSA-2', 'GHSA-3', 'GHSA-4'], direct=True, repository='https://github.com/a/fixed', compare='https://github.com/a/fixed/compare/x...y'),
            self.line('a/patched', patches=['patches/p.patch'], constraint_was='^1'),
            self.line('a/major', jump='major', to='2.0.0'),
            self.line('a/companion'),
        ]), 0)
        self.assertIn('| Package | From → To | Jump | Source | Fixes | Notes |', text)
        self.assertIn('| `a/fixed` | `1.0.0 → 1.0.1` | patch | [repo](https://github.com/a/fixed) · [diff](https://github.com/a/fixed/compare/x...y) | `GHSA-1`, `GHSA-2`, `GHSA-3` +1 | direct |', text)
        self.assertIn('| `a/patched` | `1.0.0 → 1.0.1` | patch | — | — | patched, constraint changed |', text)
        self.assertIn('| `a/major` | `1.0.0 → 2.0.0` | major | — | — | — |', text)
        self.assertNotIn('| `a/companion` |', text)

    def test_a_pipe_in_a_name_or_version_cannot_split_a_table_cell_and_a_missing_version_is_a_dash(self):
        text = brief.render_lock_report(self.report([
            self.line('a/b|c', fixes=['GHSA-1|2'], **{'from': 'dev-x|y', 'to': None}),
            self.line('a/added', patches=['p.patch'], **{'from': None, 'to': '1.0'}),
        ]), 0)
        rows = [row for row in text.split('\n') if row.startswith('| `a/')]
        self.assertEqual(['| `a/b\\|c` | `dev-x\\|y → —` | patch | — | `GHSA-1\\|2` | — |',
                          '| `a/added` | `— → 1.0` | patch | — | — | patched |'], rows)

