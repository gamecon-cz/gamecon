class EndToEndTest(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.repository = os.path.join(self.directory.name, 'repository')
        os.makedirs(self.repository)
        self.git('init', '--quiet', '-b', 'main')
        self.git('config', 'user.email', 'test@example.com')
        self.git('config', 'user.name', 'Test')
        self.git('config', 'commit.gpgsign', 'false')

    def tearDown(self):
        self.directory.cleanup()

    def git(self, *arguments):
        return subprocess.run(['git', '-C', self.repository, *arguments], check=True, capture_output=True, text=True).stdout.strip()

    def commit(self, files):
        for path, content in files.items():
            os.makedirs(os.path.dirname(os.path.join(self.repository, path)), exist_ok=True)
            with open(os.path.join(self.repository, path), 'w') as handle:
                handle.write(content)
        self.git('add', '-A')
        self.git('commit', '--quiet', '-m', 'commit')

    def outside(self, name):
        return os.path.join(self.directory.name, name)

    def run_command(self, arguments, output_name):
        output_path = self.outside(output_name)
        if os.path.exists(output_path):
            os.remove(output_path)
        brief.main([*arguments, '--output', output_path])
        if not os.path.exists(output_path):
            return None
        with open(output_path) as output_file:
            return output_file.read()

    def run_brief(self):
        return self.run_command(['brief', '--repository', self.repository, '--base-sha', 'HEAD~1', '--head-sha', 'HEAD'], 'brief.md')

    def run_splice(self, body, brief_text):
        with open(self.outside('body.md'), 'w') as handle:
            handle.write(body)
        with open(self.outside('brief-input.md'), 'w') as handle:
            handle.write(brief_text)
        return self.run_command(['splice', '--body-file', self.outside('body.md'), '--brief-file', self.outside('brief-input.md')], 'new-body.md')

    def run_both(self, body):
        brief_text = self.run_brief()
