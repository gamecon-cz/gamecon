<?php

declare(strict_types=1);

/**
 * Masks that dg/ftp-deployment appends after the configured ones, so they override their exceptions. rsync gets them as
 * sender-only rules: never sent, and a leftover on the server is deleted unless a `P` rule or an exclude of the other
 * masks covers it (a `.gitkeep` in the uploads, a `.bak` in the content). A mask added by a library upgrade is treated
 * the same way, so check that it names no server data.
 *
 * @see \Deployment\CliRunner::$ignoreMasks
 * @return list<string>
 */
function getDefaultIgnoreMasks(): array
{
    return ['*.bak', '.svn', '.git*', 'Thumbs.db', '.DS_Store', '.idea', '.claude'];
}

/**
 * Paths that appear on the server at runtime or were uploaded by hand, so git lacks them. FTP never deleted them,
 * because it deleted only what it had uploaded; rsync `--delete` deletes everything not listed here or covered by an exclude of the project masks.
 *
 * @return list<string>
 */
function getRsyncProtectedPaths(): array
{
    return [
        '/web/soubory/systemove/*/*', // uploaded photos, avatars and images
        '/admin/*.sql.gz', // temporary database dumps
        '/cache/*', // also cache/private<database name>, created by the application
        '/symfony/config/reference.php', // generated by Symfony on the server
        '/web/soubory/styl-rocnikovy/***', // page background uploaded by hand, referenced from styl.less
        '/web/soubory/blackarrow/qrka/***', // logos uploaded by hand for web/moduly/qrka.php
        '/nastaveni/google_api_client_secret*.json', // copied to the server by hand, see nastaveni/.gitignore
        '/nastaveni/google-api-client-secret.json', // the masks from nastaveni/.gitignore are rooted in the repository, so they miss these
    ];
}

/**
 * Translates dg/ftp-deployment masks (the last match wins, `!` is an exception) to rsync filters (the first match wins)
 * that select the same files, see docs/generated/nasazeni-rsync.md. Protected paths go first as `P` rules; after the
 * masks, the `+` exceptions would match them first and leave a server-only `.htaccess` deletable. The sender-only masks
 * (plain names) become `H` rules after them, not excludes, see the same document.
 *
 * @param list<string> $ignoreMasks
 * @param list<string> $protectedPaths
 * @param list<string> $senderOnlyMasks
 * @return list<string>
 */
function buildRsyncFilters(array $ignoreMasks, array $protectedPaths = [], array $senderOnlyMasks = []): array
{
    assertMasksTranslatable(array_merge($ignoreMasks, $senderOnlyMasks));

    $filters = [];
    foreach ($protectedPaths as $protectedPath) {
        $filters[] = "P {$protectedPath}";
    }
    foreach (array_reverse($senderOnlyMasks) as $mask) {
        $mask = trim($mask);
        if (str_starts_with($mask, '!') || str_contains($mask, '/')) {
            throw new \LogicException("Maska '{$mask}' pro odesílatele musí být jen název, bez výjimky a bez lomítka");
        }
        if ($mask !== '') {
            $filters[] = 'H ' . foldRsyncPatternCase($mask);
        }
    }
    foreach (array_reverse($ignoreMasks) as $mask) {
        $mask = trim($mask);
        if ($mask === '') {
            continue;
        }
        $isException = str_starts_with($mask, '!');
        $pattern     = $isException
            ? substr($mask, 1)
            : $mask;
        if (str_contains($pattern, '/') && !str_starts_with($pattern, '/')) {
            $pattern = '/' . $pattern;
        }
        $filters[] = ($isException
            ? '+ '
            : '- ') . foldRsyncPatternCase($pattern);
        if ($isException) {
            $parents = explode('/', trim($pattern, '/'));
            array_pop($parents);
            for ($depth = 1; $depth <= count($parents); $depth++) {
                $filters[] = '+ ' . foldRsyncPatternCase('/' . implode('/', array_slice($parents, 0, $depth)) . '/');
            }
        }
    }

    return array_values(array_unique($filters));
}

/**
 * Refuses the mask shapes the translation does not select exactly like the library: `[`, `\` and `**`, which rsync reads
 * differently, and an exception inside a directory that an earlier mask ignores, which rsync would not keep ignored.
 *
 * @param list<string> $ignoreMasks
 */
function assertMasksTranslatable(array $ignoreMasks): void
{
    $ignoringPatterns = [];
    foreach ($ignoreMasks as $mask) {
        $mask        = trim($mask);
        $isException = str_starts_with($mask, '!');
        $pattern     = $isException
            ? substr($mask, 1)
            : $mask;
        if (preg_match('~[\\\\\[]|\*\*~', $pattern) === 1) {
            throw new \LogicException("Maska '{$mask}' obsahuje [, \\ nebo **, což rsync vykládá jinak než dg/ftp-deployment");
        }
        $isRooted = str_contains($pattern, '/');
        if (!$isException) {
            $ignoringPatterns[] = [$isRooted
                ? '/' . trim($pattern, '/')
                : $pattern, $isRooted];
            continue;
        }
        $parents = explode('/', trim($pattern, '/'));
        array_pop($parents);
        for ($depth = 1; $depth <= count($parents); $depth++) {
            $parent = '/' . implode('/', array_slice($parents, 0, $depth));
            foreach ($ignoringPatterns as [$ignoringPattern, $ignoringIsRooted]) {
                // the parent can hold a wildcard too, so a literal ignored directory matches it the other way round
                $matches = $ignoringIsRooted
                    ? fnmatch($ignoringPattern, $parent, FNM_PATHNAME | FNM_CASEFOLD) || fnmatch($parent, $ignoringPattern, FNM_PATHNAME | FNM_CASEFOLD)
                    : fnmatch($ignoringPattern, basename($parent), FNM_CASEFOLD);
                if ($matches) {
                    throw new \LogicException("Výjimka '{$mask}' leží ve složce '{$parent}', kterou ignoruje '{$ignoringPattern}'; rsync by z ní nahrál víc než dg/ftp-deployment");
                }
            }
        }
    }
}

function foldRsyncPatternCase(string $pattern): string
{
    $folded = '';
    $length = strlen($pattern);
    for ($index = 0; $index < $length; $index++) {
        $character = $pattern[$index];
        $folded .= ctype_alpha($character)
            ? '[' . strtolower($character) . strtoupper($character) . ']'
            : $character;
    }

    return $folded;
}

/**
 * @param list<string> $filters
 * @return list<string> arguments for {@see call_check()}
 */
function buildRsyncCommand(
    string $sourceDir,
    string $target,
    array  $filters,
    string $keyFile,
    string $knownHostsFile,
    ?int   $sshPort,
    ?int   $maxDelete,
    bool   $dryRun,
): array {
    $ssh = [
        'ssh',
        '-i', $keyFile,
        '-o', 'IdentitiesOnly=yes',
        '-o', 'BatchMode=yes',
        '-o', 'StrictHostKeyChecking=yes',
        '-o', 'UserKnownHostsFile=' . $knownHostsFile,
        '-o', 'GlobalKnownHostsFile=/dev/null',
        '-o', 'ConnectTimeout=30',
    ];
    if ($sshPort !== null) {
        array_push($ssh, '-p', (string)$sshPort);
    }

    $command = [
        'rsync',
        '--recursive',
        '--copy-links', // dg/ftp-deployment uploaded symlinks as the files and directories they point to
        '--checksum', // modification times differ after every checkout and composer install
        '--compress',
        '--delete-delay', // plain --delete removes files before the new ones are renamed into place
        '--delay-updates', // files get renamed into place only after all of them are uploaded
        '--verbose',
        '--timeout=600',
        '--rsh', implode(' ', $ssh),
    ];
    if ($maxDelete !== null) {
        $command[] = "--max-delete={$maxDelete}"; // makes even a --dry-run stop at the limit, so a plan must not have it
    }
    if ($dryRun) {
        $command[] = '--dry-run';
    } else {
        // a plan's captured output is cut to its last lines, which these would fill
        array_push($command, '--human-readable', '--stats');
    }
    foreach ($filters as $filter) {
        $command[] = "--filter={$filter}";
    }
    $command[] = rtrim($sourceDir, '/') . '/';
    $command[] = $target;

    return $command;
}

/**
 * Limit for everything outside vendor/. Those deletions come a few at a time, so it is low enough to notice a broken
 * filter or protected path.
 */
function getRsyncMaxDeleteProject(): int
{
    return parseRsyncDeleteLimit('DEPLOY_RSYNC_MAX_DELETE_PROJECT', 500);
}

/**
 * vendor/ is committed, so one dependency update can delete thousands of files.
 */
function getRsyncMaxDeleteVendor(): int
{
    return parseRsyncDeleteLimit('DEPLOY_RSYNC_MAX_DELETE_VENDOR', 5000);
}

function parseRsyncDeleteLimit(string $variableName, int $default): int
{
    $limit = (string)getenv($variableName);
    if ($limit === '') {
        return $default;
    }
    if (!ctype_digit($limit) || strlen($limit) > 9) {
        throw new \RuntimeException("{$variableName} musí být celé číslo od 0 do 999999999, je '{$limit}'");
    }

    return (int)$limit;
}

/**
 * @param list<string> $deletions the "deleting …" lines
 * @return array{vendor: list<string>, project: list<string>}
 */
function splitRsyncDeletionsByVendor(array $deletions): array
{
    $vendor = array_values(array_filter(
        $deletions,
        static fn(string $deletion) => str_starts_with($deletion, 'deleting vendor/'),
    ));

    return ['vendor' => $vendor, 'project' => array_values(array_diff($deletions, $vendor))];
}

/**
 * A server-only directory that protected files keep: a dry run lists it as deleted, the real run only prints this.
 *
 * @param list<string> $planOutput
 * @return list<string> the directories, each ending with a slash
 */
function getKeptRsyncDirectories(array $planOutput): array
{
    $kept = [];
    foreach ($planOutput as $line) {
        if (preg_match('~^cannot delete non-empty directory: (.+?)/?$~', $line, $matches) === 1) {
            $kept[] = $matches[1] . '/';
        }
    }

    return $kept;
}

/**
 * @param list<string> $planOutput
 * @return list<string> the "deleting …" lines, without the kept directories
 */
function getPlannedRsyncDeletions(array $planOutput): array
{
    $kept = array_flip(getKeptRsyncDirectories($planOutput));

    return array_values(array_filter(
        $planOutput,
        static fn(string $line) => str_starts_with($line, 'deleting ')
            && !isset($kept[rtrim(substr($line, strlen('deleting ')), '/') . '/']),
    ));
}

function getRsyncSshPort(): ?int
{
    $port = (string)getenv('DEPLOY_SSH_PORT');
    if ($port === '') {
        return null;
    }
    if (!ctype_digit($port) || (int)$port < 1 || (int)$port > 65535) {
        throw new \RuntimeException("DEPLOY_SSH_PORT musí být číslo portu od 1 do 65535, je '{$port}'");
    }

    return (int)$port;
}

/**
 * The key and known_hosts come from environment variables (GitHub secrets), ssh reads them from files.
 *
 * Every run first plans with `--dry-run` and stops when more items would be deleted than allowed, before anything
 * changes; `--max-delete` alone only stops the deleting after that many are gone, so only the upload carries it,
 * set to what the plan found plus a small reserve.
 */
function uploadFilesViaRsync(
    string $sourceDir,
    array  $ignoreMasks,
    string $target,
    bool   $dryRun,
): void {
    $privateKey = (string)getenv('DEPLOY_SSH_KEY');
    $knownHosts = (string)getenv('DEPLOY_SSH_KNOWN_HOSTS');
    if (trim($privateKey) === '' || trim($knownHosts) === '') {
        throw new \RuntimeException('Nasazení přes rsync vyžaduje DEPLOY_SSH_KEY a DEPLOY_SSH_KNOWN_HOSTS, bez known_hosts by se server neověřoval');
    }
    $sshPort          = getRsyncSshPort();
    $maxDeleteProject = getRsyncMaxDeleteProject();
    $maxDeleteVendor  = getRsyncMaxDeleteVendor();

    $keyFile        = null;
    $knownHostsFile = null;
    try {
        $keyFile        = tempnam(sys_get_temp_dir(), 'gamecon-deploy-key-');
        $knownHostsFile = tempnam(sys_get_temp_dir(), 'gamecon-deploy-hosts-');
        if ($keyFile === false || $knownHostsFile === false) {
            throw new \RuntimeException('Nejde vytvořit dočasné soubory pro klíč a known_hosts');
        }
        // ssh rejects a key without a trailing newline or with CRLF line endings
        file_put_contents($keyFile, rtrim(str_replace("\r\n", "\n", $privateKey)) . "\n");
        file_put_contents($knownHostsFile, rtrim(str_replace("\r\n", "\n", $knownHosts)) . "\n");

        $filters      = buildRsyncFilters($ignoreMasks, getRsyncProtectedPaths(), getDefaultIgnoreMasks());
        $buildCommand = static fn(bool $dryRunCommand, ?int $maxDeleteInCommand) => buildRsyncCommand(
            sourceDir: $sourceDir,
            target: $target,
            filters: $filters,
            keyFile: $keyFile,
            knownHostsFile: $knownHostsFile,
            sshPort: $sshPort,
            maxDelete: $maxDeleteInCommand,
            dryRun: $dryRunCommand,
        );

        msg('plánuji nasazení přes rsync, nic se zatím nemění');
        $plan            = call_check_capture($buildCommand(true, null));
        $deletions       = getPlannedRsyncDeletions($plan);
        $keptDirectories = count(getKeptRsyncDirectories($plan));
        $deletionsByArea = splitRsyncDeletionsByVendor($deletions);
        $projectCount    = count($deletionsByArea['project']);
        $vendorCount     = count($deletionsByArea['vendor']);
        $projectExceeded = $projectCount > $maxDeleteProject;
        $vendorExceeded  = $vendorCount > $maxDeleteVendor;
        // vendor/ usually has far more deletions than the rest, so the area that tripped its limit is listed first
        $shown = $dryRun
            ? $plan
            : array_slice(
                $vendorExceeded && !$projectExceeded
                    ? array_merge($deletionsByArea['vendor'], $deletionsByArea['project'])
                    : array_merge($deletionsByArea['project'], $deletionsByArea['vendor']),
                0,
                50,
            );
        if ($shown !== []) {
            echo implode(PHP_EOL, $shown) . PHP_EOL;
        }
        if (!$dryRun && count($deletions) > 50) {
            echo '… a dalších ' . (count($deletions) - 50) . PHP_EOL;
        }
        msg(count($deletions) . " položek by rsync smazal ({$projectCount} mimo vendor/, {$vendorCount} ve vendor/" . ($keptDirectories > 0
            ? ", bez {$keptDirectories} složek, které nechají chráněné soubory"
            : '') . ')');
        $exceeded = [];
        if ($projectExceeded) {
            $exceeded[] = "{$projectCount} položek mimo vendor/, víc než DEPLOY_RSYNC_MAX_DELETE_PROJECT ({$maxDeleteProject}), zkontroluj chráněné cesty a masky";
        }
        if ($vendorExceeded) {
            $exceeded[] = "{$vendorCount} položek ve vendor/, víc než DEPLOY_RSYNC_MAX_DELETE_VENDOR ({$maxDeleteVendor}), zkontroluj, co se změnilo v závislostech";
        }
        if ($exceeded !== []) {
            throw new \RuntimeException(
                'rsync by smazal ' . implode('; ', $exceeded) . ' – nic se nezměnilo. Jestli je to správně, zvyš příslušný limit',
            );
        }
        if ($dryRun) {
            return;
        }

        msg('synchronizuji soubory na vzdáleném serveru přes rsync');
        // at most what the plan approved, plus the kept directories (a refused removal counts as skipped once the limit is
        // reached) and a few items that appear between the plan and the upload: failing after the new files are live but
        // before the migrations run is worse than deleting a stray file
        $itemsAllowedAfterThePlan = 20;
        call_check($buildCommand(false, count($deletions) + $keptDirectories + $itemsAllowedAfterThePlan));
    } finally {
        foreach ([$keyFile, $knownHostsFile] as $temporaryFile) {
            if (is_string($temporaryFile) && is_file($temporaryFile)) {
                unlink($temporaryFile);
            }
        }
    }
}
